def text_to_phonemes(text):
    phonemes = g2p(text)

    phonemes = [
        p for p in phonemes
        if p.strip() and not re.match(r"^[.,!?;:'\"]$", p)
    ]

    phonemes = [re.sub(r"\d", "", p) for p in phonemes]

    return phonemes


def phoneme_error_rate(reference, prediction):
    ref = text_to_phonemes(reference)
    hyp = text_to_phonemes(prediction)

    dp = [[0] * (len(hyp) + 1) for _ in range(len(ref) + 1)]

    for i in range(len(ref) + 1):
        dp[i][0] = i

    for j in range(len(hyp) + 1):
        dp[0][j] = j

    for i in range(1, len(ref) + 1):
        for j in range(1, len(hyp) + 1):
            if ref[i - 1] == hyp[j - 1]:
                cost = 0
            else:
                cost = 1

            dp[i][j] = min(
                dp[i - 1][j] + 1,
                dp[i][j - 1] + 1,
                dp[i - 1][j - 1] + cost
            )

    if len(ref) == 0:
        return 0.0 if len(hyp) == 0 else 1.0

    return dp[-1][-1] / len(ref)


