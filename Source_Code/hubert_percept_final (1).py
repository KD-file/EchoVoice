# ===== Stage 1: preprocessing constants and helpers =====
# Manuscript: 16 kHz mono audio, energy-thresholded VAD that trims leading
# and trailing non-speech silences, then peak normalization to -1.0 dBFS.
import numpy as np
import librosa
import soundfile as sf

DBFS_LEVEL = -1.0  # target peak headroom, -1.0 dBFS
VAD_DB_THRESHOLD = -35.0  # RMS below this is treated as silence
VAD_FRAME_MS = 20.0
VAD_HOP_MS = 10.0
VAD_MIN_PAD_S = 0.05


def vad_trim(waveform, sampling_rate=TARGET_SAMPLE_RATE):
    """Energy-thresholded VAD: keep the voiced span plus a small padding."""
    waveform = np.asarray(waveform, dtype=np.float32)
    frame = int(sampling_rate * VAD_FRAME_MS / 1000.0)
    hop = int(sampling_rate * VAD_HOP_MS / 1000.0)

    if len(waveform) < frame:
        return waveform

    rms = np.zeros(1 + (len(waveform) - frame) // hop, dtype=np.float32)
    for i, start in enumerate(range(0, len(waveform) - frame + 1, hop)):
        rms[i] = np.sqrt(np.mean(waveform[start:start + frame] ** 2) + 1e-12)

    voiced = (20.0 * np.log10(rms + 1e-12)) > VAD_DB_THRESHOLD

    if not np.any(voiced):
        return waveform

    idx = np.where(voiced)[0]
    start_ms = int(idx[0] * hop)
    end_ms = int(idx[-1] * hop + frame)
    pad = int(sampling_rate * VAD_MIN_PAD_S)

    return waveform[max(0, start_ms - pad):min(len(waveform), end_ms + pad)]


def peak_normalize(waveform, target_db=DBFS_LEVEL):
    """Peak-normalize the signal to 'target_db' dBFS (e.g. -1.0 dBFS)."""
    waveform = np.asarray(waveform, dtype=np.float32)
    peak = np.max(np.abs(waveform))
    if peak <= 1e-12:
        return waveform
    gain = 10.0 ** (target_db / 20.0)
    return waveform * (gain / peak)


