# ===== Stage 2 (b) + (c): stochastic augmentation in the data collator =====
# Manuscript: augmentations are applied DYNAMICALLY DURING BATCH TRAINING -
# not cached at map()-time - so I apply them in the collator, which runs on
# every batch:
#   - pitch-shift each clip by a random n_steps in [-3.0, +4.0] semitones,
#     keeping the duration unchanged (librosa phase vocoder).
#   - mix in an ambient-noise segment at a random SNR in [0, 15] dB.
# Set NOISE_DIR to a folder of real ambient clips if available; otherwise a
# small synthetic colored-noise bank is generated so the pipeline still runs.
NOISE_DIR = None  # e.g. "/content/drive/MyDrive/datasets/noise" (optional)
AUGMENT_PROB = 0.8
PITCH_SEMITONES = (-3.0, 4.0)
SNR_DB_RANGE = (0.0, 15.0)


def _synthetic_noise_bank(sample_rate=TARGET_SAMPLE_RATE,
                          n_segments=5, seconds=5.0):
    rng = np.random.default_rng(0)
    bank = []
    for _ in range(n_segments):
        white = rng.standard_normal(int(sample_rate * seconds)).astype(np.float32)
        brown = np.cumsum(white, dtype=np.float32)
        brown = brown - np.mean(brown)
        denom = np.std(brown) + 1e-12
        bank.append((0.35 * white + 0.65 * (brown / denom)).astype(np.float32))
    return bank


from dataclasses import dataclass
from typing import Dict, List, Optional, Union
import torch
from transformers import TrainerCallback

@dataclass
class DataCollatorCTCWithPadding:
    processor: object
    padding: Union[bool, str] = True
    augment: bool = False
    sample_rate: int = TARGET_SAMPLE_RATE
    augment_prob: float = AUGMENT_PROB
    pitch_semitones: tuple = PITCH_SEMITONES
    snr_db: tuple = SNR_DB_RANGE
    noise_dir: Optional[str] = NOISE_DIR

    def __post_init__(self):
        self._noise_bank = None

    def _load_noise_bank(self):
        if self._noise_bank is None:
            if self.noise_dir and os.path.isdir(self.noise_dir):
                clips = []
                for filename in sorted(os.listdir(self.noise_dir)):
                    if not filename.lower().endswith((".wav", ".flac", ".ogg", ".mp3")):
                        continue
                    try:
                        clip, sr = sf.read(
                            os.path.join(self.noise_dir, filename),
                            dtype="float32"
                        )
                        if sr != self.sample_rate:
                            clip = librosa.resample(
                                clip, orig_sr=sr, target_sr=self.sample_rate
                            ).astype(np.float32)
                        clips.append(clip)
                    except Exception:
                        continue
                self._noise_bank = clips if clips else _synthetic_noise_bank(self.sample_rate)
            else:
                self._noise_bank = _synthetic_noise_bank(self.sample_rate)
        return self._noise_bank

    def _apply_pitch_shift(self, waveform):
        n_steps = float(np.random.uniform(*self.pitch_semitones))
        if abs(n_steps) < 0.1:
            return waveform
        return librosa.effects.pitch_shift(
            waveform, sr=self.sample_rate, n_steps=n_steps
        ).astype(np.float32)

    def _apply_noise_mix(self, waveform):
        bank = self._load_noise_bank()
        clip = bank[np.random.randint(0, len(bank))]

        n = len(waveform)
        if len(clip) < n:
            start = 0
            clip = np.resize(clip, n)
        else:
            start = np.random.randint(0, len(clip) - n + 1)
        segment = clip[start:start + n]

        sig_power = np.mean(waveform ** 2) + 1e-12
        noise_power = np.mean(segment ** 2) + 1e-12
        snr_db = float(np.random.uniform(*self.snr_db))  # positive = signal louder
        target_noise_power = sig_power / (10.0 ** (snr_db / 10.0))
        scale = np.sqrt(target_noise_power / noise_power)

        return (waveform + scale * segment).astype(np.float32)

    def __call__(self, features: List[Dict]) -> Dict[str, torch.Tensor]:
        input_features = [
            {"input_values": feature["input_values"]}
            for feature in features
        ]

        label_features = [
            {"input_ids": feature["labels"]}
            for feature in features
        ]

        batch = self.processor.feature_extractor.pad(
            input_features,
            padding=self.padding,
            return_attention_mask=True,
            return_tensors="pt"
        )

        labels_batch = self.processor.tokenizer.pad(
            label_features,
            padding=self.padding,
            return_tensors="pt"
        )

        attention_mask = batch.pop("attention_mask", None)

        # Stochastic domain adaptation, recomputed on every training batch.
        if self.augment:
            values = batch["input_values"]
            for i in range(values.shape[0]):
                length = int(attention_mask[i].sum().item())
                if length <= 0:
                    continue
                waveform = values[i, :length].numpy().astype(np.float32)

                if np.random.random() < self.augment_prob:
                    waveform = self._apply_pitch_shift(waveform)
                if np.random.random() < self.augment_prob:
                    waveform = self._apply_noise_mix(waveform)

                values[i, :length] = torch.from_numpy(waveform)

        labels = labels_batch["input_ids"].masked_fill(
            labels_batch.attention_mask.ne(1),
            -100
        )

        batch["labels"] = labels

        return batch


data_collator = DataCollatorCTCWithPadding(
    processor=processor,
    padding=True
)


def _set_augmentation(state):
    """Enable the full augmentation pipeline for training; disable it for
    evaluation so WER/PER benchmarks measure the model, not the noise."""
    data_collator.augment = state
    model.config.apply_spec_augment = state


class ToggleAugmentationCallback(TrainerCallback):
    def on_train_begin(self, args, state, control, **kwargs):
        _set_augmentation(True)

    def on_eval_begin(self, args, state, control, **kwargs):
        _set_augmentation(False)


